/**
 * Universal Intent Parser & Auto-Router for LAYA AI Orchestrator
 * Analyzes any natural language prompt and routes to the correct ServiceNow table API endpoint
 * with extracted field values.
 */

export interface ParsedIntentResult {
  table: string;
  payload: Record<string, any>;
  summary: string;
}

export function parsePromptToServiceNowIntent(prompt: string): ParsedIntentResult {
  const p = prompt.toLowerCase();
  
  // 1. User Creation
  if (p.includes('user') || p.includes('employee') || p.includes('person') || p.includes('onboard')) {
    const nameMatch = prompt.match(/(?:named|called|user|employee)\s+([A-Z][a-zA-Z\s]+)(?:\s+with|\s+as|\.|$|,)/i);
    const fullName = nameMatch ? nameMatch[1].trim() : 'Alex Morgan';
    const nameParts = fullName.split(' ');
    const firstName = nameParts[0] || 'Alex';
    const lastName = nameParts.slice(1).join(' ') || 'Morgan';
    const email = `${firstName.toLowerCase()}.${lastName.toLowerCase()}@example.com`;

    return {
      table: 'sys_user',
      payload: {
        user_name: `${firstName.toLowerCase()}.${lastName.toLowerCase()}`,
        first_name: firstName,
        last_name: lastName,
        email,
        title: p.includes('admin') ? 'ServiceNow Administrator' : p.includes('manager') ? 'IT Service Manager' : 'Enterprise Employee',
        active: 'true',
        department: 'IT Engineering'
      },
      summary: `Created User [sys_user]: ${firstName} ${lastName} (${email})`
    };
  }

  // 2. Incident Creation
  if (p.includes('incident') || p.includes('ticket') || p.includes('issue') || p.includes('outage') || p.includes('error')) {
    let shortDesc = prompt.length > 80 ? prompt.substring(0, 77) + '...' : prompt;
    let priority = '3'; // Moderate
    if (p.includes('p1') || p.includes('critical') || p.includes('urgent') || p.includes('sev 1')) {
      priority = '1';
    } else if (p.includes('p2') || p.includes('high')) {
      priority = '2';
    }

    return {
      table: 'incident',
      payload: {
        short_description: shortDesc,
        description: `Auto-created by LAYA AI Orchestrator for requirement: ${prompt}`,
        priority,
        impact: priority,
        urgency: priority,
        category: p.includes('email') || p.includes('vpn') || p.includes('network') ? 'Network' : 'Inquiry / Help',
        state: '1', // New
        contact_type: 'AI Virtual Agent'
      },
      summary: `Created Incident [incident] (Priority ${priority}): "${shortDesc}"`
    };
  }

  // 3. Change Request
  if (p.includes('change') || p.includes('chg') || p.includes('cab') || p.includes('release') || p.includes('deployment')) {
    let shortDesc = prompt.length > 80 ? prompt.substring(0, 77) + '...' : prompt;
    return {
      table: 'change_request',
      payload: {
        short_description: shortDesc,
        description: `Emergency CAB release package generated by LAYA: ${prompt}`,
        type: p.includes('emergency') ? 'Emergency' : 'Normal',
        risk: '2',
        priority: '2',
        state: '-5' // New
      },
      summary: `Created Change Request [change_request]: "${shortDesc}"`
    };
  }

  // 4. Problem Record
  if (p.includes('problem') || p.includes('root cause') || p.includes('known error')) {
    let shortDesc = prompt.length > 80 ? prompt.substring(0, 77) + '...' : prompt;
    return {
      table: 'problem',
      payload: {
        short_description: shortDesc,
        description: `Problem investigation initiated by LAYA AI: ${prompt}`,
        priority: '2',
        state: '1'
      },
      summary: `Created Problem Record [problem]: "${shortDesc}"`
    };
  }

  // 5. Service Catalog Item (sc_cat_item)
  if (p.includes('catalog') || p.includes('item') || p.includes('request item') || p.includes('store') || p.includes('laptop')) {
    let itemName = prompt.length > 60 ? prompt.substring(0, 57) + '...' : prompt;
    return {
      table: 'sc_cat_item',
      payload: {
        name: itemName,
        short_description: `Service Catalog item created by LAYA: ${prompt}`,
        price: '1250.00',
        active: 'true',
        no_notifications: 'false',
        desktop_item: 'true'
      },
      summary: `Created Service Catalog Item [sc_cat_item]: "${itemName}"`
    };
  }

  // 6. Business Rule (sys_script)
  if (p.includes('business rule') || p.includes('script') || p.includes('rule') || p.includes('trigger')) {
    return {
      table: 'sys_script',
      payload: {
        name: `LAYA_Auto_${Date.now().toString().slice(-4)}`,
        collection: 'incident',
        when: 'before',
        active: 'true',
        insert: 'true',
        update: 'true',
        script: `(function executeRule(current, previous) {\n    // Auto-generated Business Rule by LAYA for: ${prompt}\n    if (current.priority == 1) {\n        gs.addInfoMessage('P1 Incident Security Audit Triggered.');\n    }\n})(current, previous);`
      },
      summary: `Created Business Rule [sys_script] on table [incident]`
    };
  }

  // 7. Default Universal Fallback -> Incident table
  let shortDesc = prompt.length > 80 ? prompt.substring(0, 77) + '...' : prompt;
  return {
    table: 'incident',
    payload: {
      short_description: shortDesc,
      description: `Universal intent execution by LAYA: ${prompt}`,
      priority: '3',
      state: '1'
    },
    summary: `Created ServiceNow Record [incident]: "${shortDesc}"`
  };
}
